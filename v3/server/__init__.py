"""西瓜todo 同步服务端。

刻意只用 Python 标准库（``http.server`` + ``sqlite3``），服务器上不需要
``pip install`` 任何东西，常驻内存约 15-20MB，适合小配置机器。

设计取舍：

- **服务端不理解待办的字段**：整条待办以 JSON 原样存进一列，服务端只看
  ``id`` / ``updated_at`` / ``deleted`` 三个同步元数据。以后客户端加字段，
  服务端不用跟着改，也不用做数据库迁移。
- **一个接口完成推拉**：``POST /api/sync`` 一次往返既上传本地改动又拉取远端改动，
  减少弱网下的失败面。
- **顺便托管网页**：手机端 PWA 由同一个服务发出去，页面与接口同源，
  从而绕开「HTTPS 页面不能请求 HTTP 接口」的混合内容限制，也不需要 CORS。

启动：

    python3 -m server --host 0.0.0.0 --port 52121
"""

